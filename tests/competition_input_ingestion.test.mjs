import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { chmodSync, existsSync, lstatSync, mkdirSync, mkdtempSync, readFileSync, realpathSync, symlinkSync, writeFileSync, statSync, rmSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { extractCompetitionInputPaths, ingestCompetitionInputs } from "../scripts/ingest_competition_inputs.mjs";

const root = mkdtempSync(join(tmpdir(), "ctf-c-input-ingestion-"));
const input = join(root, "Downloads");
const runtime = join(process.cwd(), ".ctf-c", "competition-runs", "input-test");
const outside = join(root, "outside.txt");
mkdirSync(input, { recursive: true, mode: 0o700 });
rmSync(runtime, { recursive: true, force: true });
mkdirSync(runtime, { recursive: true, mode: 0o700 });
writeFileSync(outside, "outside");
writeFileSync(join(input, "outside.txt"), "archive escape\n");

const textPath = join(input, "creds-dump.txt");
const pythonPath = join(input, "app.py");
const sqlitePath = join(input, "users.db");
const spacedPath = join(input, "hello world.txt");
const parenthesizedPath = join(input, "app (1).py");
const tarRoot = join(input, "tar-source");
const zipRoot = join(input, "zip-source");
const copiedArchiveRoot = join(input, "archive-source");
mkdirSync(tarRoot, { recursive: true });
mkdirSync(zipRoot, { recursive: true });
mkdirSync(copiedArchiveRoot, { recursive: true });
writeFileSync(textPath, "secret text\n");
writeFileSync(pythonPath, "print('fixture')\n");
writeFileSync(spacedPath, "space fixture\n");
writeFileSync(parenthesizedPath, "parenthesis fixture\n");
execFileSync("/usr/bin/sqlite3", [sqlitePath, "create table users(name text); insert into users values ('fixture');"]);
writeFileSync(join(tarRoot, "module.py"), "print('tar')\n");
writeFileSync(join(zipRoot, "page.html"), "<p>zip</p>\n");
writeFileSync(join(copiedArchiveRoot, "archive.txt"), "archive fixture\n");
const tarPath = join(input, "source.tar.gz");
const plainTarPath = join(input, "source.tar");
const tgzPath = join(input, "source.tgz");
const zipPath = join(input, "source.zip");
const copiedArchivePath = join(input, "archive (copy).tar.gz");
execFileSync("/usr/bin/tar", ["-czf", tarPath, "-C", tarRoot, "module.py"]);
execFileSync("/usr/bin/tar", ["-cf", plainTarPath, "-C", tarRoot, "module.py"]);
execFileSync("/usr/bin/tar", ["-czf", tgzPath, "-C", tarRoot, "module.py"]);
execFileSync("/usr/bin/zip", ["-q", zipPath, "page.html"], { cwd: zipRoot });
execFileSync("/usr/bin/tar", ["-czf", copiedArchivePath, "-C", copiedArchiveRoot, "archive.txt"]);

const symlinkPath = join(input, "escaped.txt");
symlinkSync(outside, symlinkPath);
const traversalRoot = join(input, "traversal-source");
mkdirSync(traversalRoot);
const traversalPath = join(input, "traversal.tar");
execFileSync("/usr/bin/tar", ["-cf", traversalPath, "-C", traversalRoot, "../outside.txt"]);
const linkRoot = join(input, "link-source");
mkdirSync(linkRoot);
writeFileSync(join(linkRoot, "target.txt"), "target\n");
symlinkSync("target.txt", join(linkRoot, "symbolic.txt"));
execFileSync("/usr/bin/tar", ["-cf", join(input, "links.tar"), "-C", linkRoot, "target.txt", "symbolic.txt"]);
const zipLinksPath = join(input, "links.zip");
execFileSync("/usr/bin/zip", ["-q", "-y", zipLinksPath, "symbolic.txt"], { cwd: linkRoot });
const largePath = join(input, "large.tar");
const largeRoot = join(input, "large-source");
mkdirSync(largeRoot);
writeFileSync(join(largeRoot, "large.bin"), Buffer.alloc(8 * 1024 * 1024 + 1));
execFileSync("/usr/bin/tar", ["-cf", largePath, "-C", largeRoot, "large.bin"]);

const recordPath = execFileSync(process.execPath, [join(process.cwd(), "scripts/create_competition_run.mjs"), "--target", "http://127.0.0.1:9", "--approve"], { encoding: "utf8", env: { ...process.env, CTFC_PROJECT_ROOT: process.cwd(), CTFC_COMPETITION_RUNTIME_ROOT: runtime } }).trim();
const original = readFileSync(textPath);
const quotedPaths = [spacedPath, parenthesizedPath, copiedArchivePath];
assert.deepEqual(extractCompetitionInputPaths(`Files: "${spacedPath}" '${parenthesizedPath}' \`${copiedArchivePath}\``), quotedPaths);
const manifest = ingestCompetitionInputs(recordPath, `Challenge http://127.0.0.1:9/flag\nFiles: "${spacedPath}" '${parenthesizedPath}' \`${copiedArchivePath}\`\n${[textPath, pythonPath, sqlitePath, tarPath, zipPath, plainTarPath, tgzPath, "/does/not/exist.txt", outside, symlinkPath, traversalPath, join(input, "links.tar"), zipLinksPath, largePath].join("\n")}`, { roots: [input] });
const record = JSON.parse(readFileSync(recordPath, "utf8"));
const sourceRoot = record.source_root;
assert.ok(sourceRoot && sourceRoot.startsWith(record.paths.run_root));
assert.equal(statSync(sourceRoot).mode & 0o777, 0o700);
assert.deepEqual(manifest.accepted.map((entry) => entry.kind), ["file", "file", "tar.gz", "file", "file", "file", "tar.gz", "zip", "tar", "tgz"]);
assert.ok(manifest.rejected.some((entry) => /does not exist/.test(entry.reason)));
assert.ok(manifest.rejected.some((entry) => /outside permitted/.test(entry.reason)));
assert.ok(manifest.rejected.some((entry) => /symbolic links/.test(entry.reason)));
assert.ok(manifest.rejected.some((entry) => /Unsafe archive entry/.test(entry.reason)));
assert.ok(manifest.rejected.some((entry) => /Archive links/.test(entry.reason)));
assert.ok(manifest.rejected.some((entry) => /Archive file size limit/.test(entry.reason)));
assert.equal(readFileSync(textPath).toString(), original.toString());
assert.equal(readFileSync(join(sourceRoot, "creds-dump.txt")).toString(), original.toString());
assert.equal(readFileSync(join(sourceRoot, "app.py")).toString(), "print('fixture')\n");
assert.equal(readFileSync(join(sourceRoot, "hello world.txt")).toString(), "space fixture\n");
assert.equal(readFileSync(join(sourceRoot, "app (1).py")).toString(), "parenthesis fixture\n");
assert.equal(statSync(join(sourceRoot, "app.py")).mode & 0o777, 0o600);
assert.equal(readFileSync(join(sourceRoot, "source", "module.py")).toString(), "print('tar')\n");
assert.equal(readFileSync(join(sourceRoot, "source-2", "page.html")).toString(), "<p>zip</p>\n");
assert.equal(readFileSync(join(sourceRoot, "source-3", "module.py")).toString(), "print('tar')\n");
assert.equal(readFileSync(join(sourceRoot, "source-4", "module.py")).toString(), "print('tar')\n");
assert.equal(readFileSync(join(sourceRoot, "archive (copy)", "archive.txt")).toString(), "archive fixture\n");
assert.equal(lstatSync(sqlitePath).isFile(), true);
assert.ok(existsSync(join(sourceRoot, "users.db")));
assert.match(execFileSync("/usr/bin/file", [join(sourceRoot, "users.db")], { encoding: "utf8" }), /SQLite/i);
assert.equal(statSync(join(sourceRoot, "supplied-inputs.json")).mode & 0o777, 0o600);
assert.equal(statSync(recordPath).mode & 0o777, 0o600);
assert.equal(statSync(record.paths.run_root).mode & 0o777, 0o700);
execFileSync("git", ["check-ignore", "-q", record.paths.run_root], { cwd: process.cwd(), stdio: "ignore" });
assert.equal(realpathSync(symlinkPath), realpathSync(outside));
assert.equal(readFileSync(outside).toString(), "outside");
rmSync(runtime, { recursive: true, force: true });
console.error("CTF_C_COMPETITION_INPUT_INGESTION=passed");
